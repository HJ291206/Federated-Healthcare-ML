"""Centralized baselines: Logistic Regression, Random Forest and a PyTorch MLP.

Run from the repository root:
    python -m ml.train_centralized [--config configs/centralized.yaml]

Protocol (the test split is touched only in step 5):
    1. Fixed stratified split (data.split_seed) into train / validation / test.
    2. Preprocessor fitted on the training rows only.
    3. Hyperparameters chosen by validation ROC-AUC (first seed).
    4. Decision thresholds chosen on validation predictions, then frozen.
    5. Test-set predictions are computed once per final model and scored.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import sys
import time
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn
import torch
import yaml
from sklearn.metrics import roc_auc_score

from ml import plotting
from ml.data import DataSplit, features_and_target, load_primary, stratified_split
from ml.data_validation import FEATURES, RAW_DIR, RESULTS_DIR, TARGET, sha256
from ml.evaluation import classification_metrics, select_thresholds
from ml.models import build_logistic_regression, build_mlp, build_random_forest, count_parameters
from ml.preprocessing import FeaturePreprocessor
from ml.training import MLPTrainConfig, fit_mlp, predict_proba

ROOT = Path(__file__).resolve().parents[1]
MODELS_DIR = ROOT / "models" / "centralized"
FIG_DIR = RESULTS_DIR / "figures"
MODEL_NAMES = ["logistic_regression", "random_forest", "mlp"]


def load_config(path: Path) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def positive_proba(model, X: np.ndarray) -> np.ndarray:
    return model.predict_proba(X)[:, 1].astype(np.float64)


def select_logistic_regression(Xtr, ytr, Xva, yva, cfg: dict, seed: int) -> tuple[dict, list[dict]]:
    rows = []
    for C in cfg["C_grid"]:
        t0 = time.perf_counter()
        model = build_logistic_regression(C, seed, cfg["max_iter"]).fit(Xtr, ytr)
        rows.append({"model": "logistic_regression", "params": json.dumps({"C": C}),
                     "val_roc_auc": roc_auc_score(yva, positive_proba(model, Xva)),
                     "fit_seconds": time.perf_counter() - t0, "seed": seed})
    best = max(rows, key=lambda r: r["val_roc_auc"])
    return json.loads(best["params"]), rows


def select_random_forest(Xtr, ytr, Xva, yva, cfg: dict, seed: int) -> tuple[dict, list[dict]]:
    rows = []
    for params in cfg["grid"]:
        t0 = time.perf_counter()
        model = build_random_forest(seed, cfg["n_estimators"], params["max_depth"], params["min_samples_leaf"],
                                    cfg["max_features"], cfg["n_jobs"]).fit(Xtr, ytr)
        rows.append({"model": "random_forest", "params": json.dumps(params),
                     "val_roc_auc": roc_auc_score(yva, positive_proba(model, Xva)),
                     "fit_seconds": time.perf_counter() - t0, "seed": seed})
        del model
    best = max(rows, key=lambda r: r["val_roc_auc"])
    return json.loads(best["params"]), rows


def environment_info(cfg: dict) -> dict:
    return {
        "python": sys.version.split()[0], "platform": platform.platform(),
        "processor": platform.processor(), "cpu_count": os.cpu_count(),
        "torch": torch.__version__, "torch_threads": cfg["mlp"]["torch_threads"],
        "cuda_available": torch.cuda.is_available(), "sklearn": sklearn.__version__,
        "numpy": np.__version__, "pandas": pd.__version__,
    }


def write_report(summary: pd.DataFrame, meta: dict, path: Path) -> None:
    def fmt(m: str, r) -> str:
        return f"{r[m + '_mean']:.4f} ± {r[m + '_std']:.4f}"

    lines = [
        "# Centralized baseline results",
        "",
        f"Generated by `python -m ml.train_centralized` on {meta['finished_at']}. Every number below is read from "
        "`results/centralized_results.csv`; nothing is typed by hand.",
        "",
        f"- Data: `{meta['data_file']}` (sha256 `{meta['data_sha256'][:16]}…`), target `{TARGET}` "
        "(1 = diabetes; 0 = no diabetes, including prediabetes; see `data/README.md`).",
        f"- Split (seed {meta['split_seed']}): " + ", ".join(
            f"{k} {v['n']:,} rows ({v['positive_rate']:.2%} positive)" for k, v in meta["split"].items()),
        f"- Model seeds: {meta['seeds']}. Values are mean ± sample std over seeds, on the **test** split.",
        f"- Imbalance handling: class weights from training labels only (LR `balanced`, RF `balanced_subsample`, "
        f"MLP `pos_weight` = {meta['mlp_pos_weight']:.4f}). Thresholds chosen on validation only.",
        "",
    ]
    for op in summary.operating_point.unique():
        sub = summary[summary.operating_point == op]
        lines += [f"## Operating point: `{op}`", "",
                  "| Model | Threshold | Accuracy | Precision (1) | Recall (1) | F1 (1) | Precision (0) | Recall (0) | ROC-AUC | PR-AUC |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        for _, r in sub.iterrows():
            lines.append(f"| {r.model} | {fmt('threshold', r)} | {fmt('accuracy', r)} | {fmt('precision_class1', r)} | "
                         f"{fmt('recall_class1', r)} | {fmt('f1_class1', r)} | {fmt('precision_class0', r)} | "
                         f"{fmt('recall_class0', r)} | {fmt('roc_auc', r)} | {fmt('pr_auc', r)} |")
        lines += ["", "| Model | TN | FP | FN | TP |", "|---|---|---|---|---|"]
        for _, r in sub.iterrows():
            lines.append(f"| {r.model} | {r.tn_mean:,.1f} | {r.fp_mean:,.1f} | {r.fn_mean:,.1f} | {r.tp_mean:,.1f} |")
        lines.append("")
    lines += [
        "## Why recall on the diabetes class matters",
        "",
        "A false negative is a person with diabetes whom the model calls healthy. In a screening use case that person "
        "is not referred for a confirmatory test (e.g. HbA1c), and untreated diabetes leads to the complications "
        "described in `data/README.md`. A false positive costs a follow-up test. Because of this asymmetry, recall "
        "(sensitivity) on class 1 is the primary threshold-dependent metric, and accuracy is not: predicting "
        f"'no diabetes' for everyone already reaches {1 - meta['split']['test']['positive_rate']:.2%} test accuracy "
        "with zero recall. Recall must be read together with class-1 precision, since raising recall by lowering "
        "the threshold increases false positives; the `val_recall_0.80` operating point makes this trade-off explicit. "
        "These are research models on self-reported survey data, not a validated screening tool.",
        "",
        f"Total runtime: {meta['runtime_seconds']['total']:.1f} s on {meta['environment']['platform']} "
        f"({meta['environment']['cpu_count']} logical CPUs, CUDA used: {meta['environment']['cuda_available']}).",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def main(config_path: Path) -> None:
    t_total = time.perf_counter()
    cfg = load_config(config_path)
    seeds = [int(s) for s in cfg["seeds"]]
    dcfg = cfg["data"]
    runtime: dict[str, float] = {}

    # 1. Data and split.
    t0 = time.perf_counter()
    df = load_primary(dcfg["file"])
    X, y = features_and_target(df)
    assert TARGET not in X.columns and list(X.columns) == FEATURES
    split = stratified_split(y, dcfg["test_size"], dcfg["val_size"], dcfg["split_seed"])
    split.save(MODELS_DIR / "split_indices.npz")
    runtime["load_and_split"] = time.perf_counter() - t0

    # 2. Preprocessing fitted on training rows only.
    t0 = time.perf_counter()
    pre = FeaturePreprocessor().fit(X.iloc[split.train])
    Xtr, Xva, Xte = (pre.transform(X.iloc[idx]) for idx in (split.train, split.val, split.test))
    ytr, yva, yte = y[split.train], y[split.val], y[split.test]
    pre.save(MODELS_DIR / "preprocessor.joblib")
    (MODELS_DIR / "preprocessor.json").write_text(json.dumps(pre.to_dict(), indent=2), encoding="utf-8")
    runtime["preprocessing"] = time.perf_counter() - t0
    split_info = {name: {"n": int(len(lbl)), "positives": int(lbl.sum()), "positive_rate": float(lbl.mean())}
                  for name, lbl in (("train", ytr), ("val", yva), ("test", yte))}
    print("Split:", json.dumps(split_info))

    # 3. Hyperparameter selection on validation (no test data passed in).
    t0 = time.perf_counter()
    lr_params, lr_rows = select_logistic_regression(Xtr, ytr, Xva, yva, cfg["logistic_regression"], seeds[0])
    rf_params, rf_rows = select_random_forest(Xtr, ytr, Xva, yva, cfg["random_forest"], seeds[0])
    selection = pd.DataFrame(lr_rows + rf_rows)
    selection["selected"] = [json.loads(p) == (lr_params if m == "logistic_regression" else rf_params)
                             for m, p in zip(selection.model, selection.params)]
    selection.to_csv(RESULTS_DIR / "centralized_model_selection.csv", index=False)
    runtime["model_selection"] = time.perf_counter() - t0
    print("Selected LR:", lr_params, " RF:", rf_params)

    mlp_cfg = MLPTrainConfig(**cfg["mlp"])
    rf_cfg = cfg["random_forest"]
    rows, histories, mlp_infos = [], [], {}
    figure_probs_test, figure_probs_val, figure_thresholds = {}, {}, {}

    t_final = time.perf_counter()
    for seed in seeds:
        for name in MODEL_NAMES:
            t0 = time.perf_counter()
            if name == "logistic_regression":
                model = build_logistic_regression(lr_params["C"], seed, cfg["logistic_regression"]["max_iter"]).fit(Xtr, ytr)
            elif name == "random_forest":
                model = build_random_forest(seed, rf_cfg["n_estimators"], rf_params["max_depth"],
                                            rf_params["min_samples_leaf"], rf_cfg["max_features"],
                                            rf_cfg["n_jobs"]).fit(Xtr, ytr)
            else:
                model, hist, info = fit_mlp(Xtr, ytr, Xva, yva, mlp_cfg, seed)
                histories.append(hist)
                mlp_infos[seed] = info
            train_seconds = time.perf_counter() - t0

            # 4. Thresholds from validation predictions only.
            p_val = predict_proba(model, Xva) if name == "mlp" else positive_proba(model, Xva)
            thresholds = select_thresholds(yva, p_val, cfg["threshold"]["recall_target"])

            # 5. Test predictions, after every choice above is frozen.
            t0 = time.perf_counter()
            p_test = predict_proba(model, Xte) if name == "mlp" else positive_proba(model, Xte)
            predict_seconds = time.perf_counter() - t0

            for op, thr in thresholds.items():
                for split_name, yt, pp in (("val", yva, p_val), ("test", yte, p_test)):
                    rows.append({"model": name, "seed": seed, "split": split_name, "operating_point": op,
                                 **classification_metrics(yt, pp, thr),
                                 "train_seconds": train_seconds, "test_predict_seconds": predict_seconds})

            if name == "mlp":
                torch.save({"state_dict": model.state_dict(), "config": model.config, "feature_names": FEATURES,
                            "n_parameters": count_parameters(model), "seed": seed},
                           MODELS_DIR / f"mlp_seed{seed}.pt")
            else:
                joblib.dump(model, MODELS_DIR / f"{name}_seed{seed}.joblib", compress=3)
            if seed == seeds[0]:
                figure_probs_test[name], figure_probs_val[name], figure_thresholds[name] = p_test, p_val, thresholds
            print(f"seed {seed} {name:20s} train {train_seconds:7.2f}s  "
                  f"val AUC {rows[-2]['roc_auc']:.4f}  test AUC {rows[-1]['roc_auc']:.4f}")
            del model

    runtime["final_training_and_evaluation"] = time.perf_counter() - t_final
    results = pd.DataFrame(rows)
    results.to_csv(RESULTS_DIR / "centralized_results.csv", index=False)
    history = pd.concat(histories, ignore_index=True)
    history.to_csv(RESULTS_DIR / "centralized_mlp_history.csv", index=False)

    metric_cols = ["threshold", "accuracy", "balanced_accuracy", "precision_class0", "recall_class0", "f1_class0",
                   "precision_class1", "recall_class1", "f1_class1", "roc_auc", "pr_auc", "tn", "fp", "fn", "tp",
                   "train_seconds"]
    test = results[results.split == "test"]
    summary = test.groupby(["operating_point", "model"], sort=False)[metric_cols].agg(["mean", "std"])
    summary.columns = [f"{m}_{s}" for m, s in summary.columns]
    summary = summary.reset_index()
    summary["n_seeds"] = len(seeds)
    summary.to_csv(RESULTS_DIR / "centralized_results_summary.csv", index=False)

    # Figures (first seed; curves on test, threshold trade-off on validation).
    s0 = seeds[0]
    plotting.plot_roc_curves(yte, figure_probs_test, FIG_DIR / "centralized_roc_curves.png",
                             f"ROC curves, test split (seed {s0})")
    plotting.plot_pr_curves(yte, figure_probs_test, FIG_DIR / "centralized_pr_curves.png",
                            f"Precision-recall curves, test split (seed {s0})")
    for op in figure_thresholds["mlp"]:
        cm_rows = test[(test.seed == s0) & (test.operating_point == op)]
        plotting.plot_confusion_matrices(cm_rows, FIG_DIR / f"centralized_confusion_{op}.png",
                                         f"Confusion matrices, test split, operating point '{op}' (seed {s0})")
    plotting.plot_mlp_history(history, FIG_DIR / "centralized_mlp_training_curves.png")
    plotting.plot_threshold_tradeoff(yva, figure_probs_val["mlp"], figure_thresholds["mlp"],
                                     FIG_DIR / "centralized_mlp_threshold_tradeoff.png",
                                     f"MLP precision / recall / F1 vs threshold, validation split (seed {s0})")

    runtime["total"] = time.perf_counter() - t_total
    meta = {
        "config_file": str(config_path.relative_to(ROOT)) if config_path.is_absolute() else str(config_path),
        "config": cfg, "seeds": seeds, "split_seed": dcfg["split_seed"],
        "data_file": dcfg["file"], "data_sha256": sha256(RAW_DIR / dcfg["file"]),
        "split": split_info, "features": FEATURES, "target": TARGET,
        "selected_hyperparameters": {"logistic_regression": lr_params, "random_forest": rf_params,
                                     "mlp": cfg["mlp"]},
        "mlp_pos_weight": mlp_infos[s0]["pos_weight"],
        "mlp_training": {str(k): {kk: vv for kk, vv in v.items() if kk != "config"} for k, v in mlp_infos.items()},
        "mlp_n_parameters": count_parameters(build_mlp(len(FEATURES), cfg["mlp"]["hidden_sizes"],
                                                       cfg["mlp"]["dropout"])),
        "train_seconds_per_model": results[results.split == "test"].drop_duplicates(["model", "seed"])
        [["model", "seed", "train_seconds"]].to_dict(orient="records"),
        "runtime_seconds": runtime, "environment": environment_info(cfg),
        "finished_at": time.strftime("%Y-%m-%d %H:%M:%S %z"),
    }
    (RESULTS_DIR / "centralized_run_metadata.json").write_text(json.dumps(meta, indent=2, default=str), encoding="utf-8")
    write_report(summary, meta, RESULTS_DIR / "centralized_report.md")

    cols = ["operating_point", "model", "threshold_mean", "accuracy_mean", "precision_class1_mean",
            "recall_class1_mean", "f1_class1_mean", "precision_class0_mean", "recall_class0_mean",
            "roc_auc_mean", "pr_auc_mean", "roc_auc_std"]
    with pd.option_context("display.width", 250, "display.max_columns", 20):
        print("\nTest split, mean over seeds:\n" + summary[cols].round(4).to_string(index=False))
    print(f"\nTotal runtime {runtime['total']:.1f}s. Results in {RESULTS_DIR}, models in {MODELS_DIR}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", type=Path, default=ROOT / "configs" / "centralized.yaml")
    main(parser.parse_args().config)
