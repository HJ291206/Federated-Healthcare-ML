ROOT = Path(__file__).resolve().parents[2]


def plot_privacy_utility(summary: pd.DataFrame, path: Path) -> None:
    metrics = [("roc_auc", "Test ROC-AUC"), ("recall_class1", "Test recall, diabetes"), ("f1_class1", "Test F1, diabetes")]
    fig, axes = plt.subplots(1, 3, figsize=(16, 4.5))
    for ax, (m, label) in zip(axes, metrics):
        for (part, algo), g in summary.groupby(["partition", "algorithm"], sort=False):
            priv = g[g.private].sort_values("epsilon_max")
            nonpriv = g[~g.private]
            line, = ax.plot(priv.epsilon_max, priv[m], marker="o", label=f"{part} / {algo}")
            for _, r in priv.iterrows():
                ax.annotate(f"σ={r.noise_multiplier:g}", (r.epsilon_max, r[m]), fontsize=7, xytext=(3, 3),
                            textcoords="offset points")
            if not nonpriv.empty:
                ax.axhline(nonpriv[m].iloc[0], color=line.get_color(), ls="--", lw=0.9)
        ax.set_xscale("log")
        ax.set(xlabel="ε (max over clients, example-level, δ fixed)", ylabel=label)
        ax.grid(alpha=0.3)
    axes[0].legend(fontsize=7)
    fig.suptitle("Privacy-utility trade-off at the validation max-F1 threshold. Dashed = non-private (no DP guarantee).", fontsize=10)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150)
    plt.close(fig)


def plot_convergence(history: pd.DataFrame, partition: str, path: Path) -> None:
    h = history[history.partition == partition]
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.3))
    for (algo, sigma), g in h.groupby(["algorithm", "noise_multiplier"], sort=False):
        label = f"{algo}, " + ("non-private" if pd.isna(sigma) else f"σ={sigma:g}")
        axes[0].plot(g["round"], g.val_roc_auc, label=label, ls="--" if pd.isna(sigma) else "-")
        axes[1].plot(g["round"], g.val_loss, label=label, ls="--" if pd.isna(sigma) else "-")
    axes[0].set(title=f"Validation ROC-AUC, partition '{partition}'", xlabel="Round", ylabel="ROC-AUC")
    axes[1].set(title="Validation loss", xlabel="Round", ylabel="Class-weighted BCE")
    for ax in axes:
        ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def write_report(meta: dict, summary: pd.DataFrame, accounting: pd.DataFrame, path: Path) -> None:
    def f(v, nd=4):
        return "n/a" if pd.isna(v) else f"{v:.{nd}f}"

    L = ["# Differential-privacy experiment", "", f"> {DISCLAIMER}", "",
         f"Generated by `python -m ml.federated.dp_experiment --config {meta['config_file']}` on {meta['finished_at']}. "
         "All numbers are read from the CSV files in this folder.", "",
         "## What is and is not claimed", "",
         "- **Non-private rows** are ordinary FedAvg/FedProx. Raw rows stay on the client (data locality), but the "
         "released model updates carry **no formal privacy guarantee**.",
         "- **Private rows** use example-level DP-SGD (Opacus " + meta["opacus_version"] + "): Poisson sampling, "
         f"per-example L2 clipping to C = {meta['privacy']['max_grad_norm']}, Gaussian noise with "
         "σ·C standard deviation, RDP accounting. The **privacy unit is one training example of one client**. "
         f"ε is reported per client at δ = {meta['privacy']['delta']:g} and summarized by the maximum over clients.",
         "- This is **not client-level DP**: it does not hide whether a whole client participated.",
         "- Hyperparameters were not tuned under DP, and the noise RNG is not cryptographically secure "
         "(`secure_mode=False`).", ""]
    L += ["## Utility (test split, validation max-F1 threshold)", "",
          "| Partition | Algorithm | σ | ε (max client) | ε (min client) | ROC-AUC | Accuracy | Recall (1) | F1 (1) | Precision (1) | Train s | MB sent |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for _, r in summary.iterrows():
        L.append(f"| {r.partition} | {r.algorithm} | {'none' if pd.isna(r.noise_multiplier) else f'{r.noise_multiplier:g}'} | "
                 f"{f(r.epsilon_max, 2)} | {f(r.epsilon_min, 2)} | {f(r.roc_auc)} | {f(r.accuracy)} | {f(r.recall_class1)} | "
                 f"{f(r.f1_class1)} | {f(r.precision_class1)} | {r.train_seconds:.1f} | {r.total_bytes / 1e6:.3f} |")
    L += ["", "Communication is identical with and without DP: DP changes how each client computes its update, not "
          "what it sends. The runtime difference is the cost of per-example gradients and noise.", "",
          "## Per-client privacy accounting", "",
          "| Partition | Algorithm | σ | Client | n_train | Sample rate | Steps | ε | δ |",
          "|---|---|---|---|---|---|---|---|---|"]
    for _, r in accounting.iterrows():
        L.append(f"| {r.partition} | {r.algorithm} | {r.noise_multiplier:g} | {r.client} | {r.n_train:,} | "
                 f"{r.sample_rate:.4f} | {r.steps} | {r.epsilon:.3f} | {r.delta:g} |")
    L += ["", "Clients with few rows have a high sampling rate (batch_size / n), so they spend budget much faster "
          "than large clients at the same σ: that is why ε varies by client.", ""]
    path.write_text("\n".join(L), encoding="utf-8")


def main(config_path: Path) -> None:
    t_total = time.perf_counter()
    cfg = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    out_dir = RESULTS_DIR / "federated" / cfg["output_tag"]
    fig_dir = out_dir / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    dcfg, fcfg, mcfg, pcfg = cfg["data"], cfg["federated"], cfg["model"], cfg["privacy"]
    seeds = [int(s) for s in cfg["seeds"]]
    recall_target = cfg["threshold"]["recall_target"]
    torch.set_num_threads(cfg.get("torch_threads", 4))

    df = load_primary(dcfg["file"])
    X, y = features_and_target(df)
    split = stratified_split(y, dcfg["test_size"], dcfg["val_size"], dcfg["split_seed"])
    test_set = set(split.test.tolist())
    local_cfg = LocalTrainConfig(lr=fcfg["lr"], batch_size=fcfg["batch_size"], local_epochs=fcfg["local_epochs"],
                                 momentum=fcfg.get("momentum", 0.0), weight_decay=fcfg.get("weight_decay", 0.0))

    def model_fn():
        return build_mlp(len(FEATURES), mcfg["hidden_sizes"], mcfg["dropout"])

    settings = [None] + [float(s) for s in pcfg["noise_multipliers"]]
    rows, hist, acct, part_tables = [], [], [], []
    for spec in cfg["partitions"]:
        part = make_partition(spec, split.train, split.val, y, cfg["num_clients"], cfg["partition_seed"])
        for c in part.clients:
            assert not (set(c.train_idx.tolist()) | set(c.val_idx.tolist())) & test_set
        part_tables.append(partition_summary(part, y))
        base_clients, fed_pre, pos_weight = build_clients(part, X, y)
        X_val = np.concatenate([c.X_val.numpy() for c in base_clients])
        y_val = np.concatenate([c.y_val.numpy() for c in base_clients]).astype(int)
        X_test, y_test = fed_pre.transform(X.iloc[split.test]), y[split.test]
        evaluator = GlobalEvaluator(X_val, y_val, X_test, y_test, pos_weight)
        print(f"\n== Partition {part.name}")
        for seed in seeds:
            for sigma in settings:
                if sigma is None:
                    clients, dp = base_clients, None
                else:
                    dp = DPConfig(noise_multiplier=sigma, max_grad_norm=pcfg["max_grad_norm"], delta=pcfg["delta"],
                                  accountant=pcfg["accountant"], poisson_sampling=pcfg["poisson_sampling"])
                # Clipped gradients are much smaller than raw ones, so DP runs may use their own learning rate
                # (chosen on validation data only, see configs/federated_dp.yaml).
                run_cfg = local_cfg if dp is None else LocalTrainConfig(
                    lr=float(pcfg.get("lr", fcfg["lr"])), batch_size=local_cfg.batch_size,
                    local_epochs=local_cfg.local_epochs, momentum=local_cfg.momentum, weight_decay=local_cfg.weight_decay)
                for algo in ["fedavg"] + [f"fedprox_mu{float(m):g}" for m in fcfg["fedprox_mu"]]:
                    if dp is not None:
                        clients = make_dp_clients(base_clients, dp)  # fresh accountants per run
                    if algo == "fedavg":
                        server = build_fedavg_server(model_fn, clients, run_cfg, fcfg["client_fraction"], seed)
                    else:
                        server = build_fedprox_server(model_fn, clients, run_cfg, fcfg["client_fraction"], seed,
                                                      float(algo.split("mu")[1]))
                    t0 = time.perf_counter()
                    h = server.fit(fcfg["rounds"], evaluator)
                    secs = time.perf_counter() - t0
                    tag = {"partition": part.name, "seed": seed, "algorithm": algo, "private": dp is not None,
                           "lr": run_cfg.lr,
                           "noise_multiplier": np.nan if dp is None else sigma,
                           "max_grad_norm": np.nan if dp is None else dp.max_grad_norm,
                           "delta": np.nan if dp is None else dp.delta}
                    eps = [c.epsilon() for c in clients] if dp is not None else []
                    if dp is not None:
                        acct += [{**tag, **c.accounting_record()} for c in clients]
                    hist += [{**tag, **r} for r in h]
                    gm = server.global_model
                    pv, pt = predict_proba(gm, evaluator.X_val), predict_proba(gm, evaluator.X_test)
                    rows += score_rows(pv, y_val, pt, y_test, recall_target, {
                        **tag, "epsilon_max": max(eps) if eps else np.nan, "epsilon_min": min(eps) if eps else np.nan,
                        "train_seconds": secs, "rounds": fcfg["rounds"],
                        "total_bytes": server.bytes_down + server.bytes_up})
                    print(f"seed {seed} {algo:15s} {'non-private' if dp is None else f'sigma={sigma:<4g}':12s} "
                          f"{secs:6.1f}s  eps_max {max(eps) if eps else float('nan'):7.3f}  "
                          f"val AUC {h[-1]['val_roc_auc']:.4f}  test AUC {h[-1]['test_roc_auc']:.4f}")

    results, history, accounting = pd.DataFrame(rows), pd.DataFrame(hist), pd.DataFrame(acct)
    summary = results[(results.split == "test") & (results.operating_point == "val_max_f1")].groupby(
        ["partition", "algorithm", "private", "noise_multiplier"], sort=False, dropna=False).mean(numeric_only=True).reset_index()
    results.to_csv(out_dir / "dp_results.csv", index=False)
    summary.to_csv(out_dir / "dp_summary.csv", index=False)
    history.to_csv(out_dir / "dp_round_history.csv", index=False)
    accounting.to_csv(out_dir / "dp_privacy_accounting.csv", index=False)
    pd.concat(part_tables).to_csv(out_dir / "client_partitions.csv", index=False)
    plot_privacy_utility(summary, fig_dir / "privacy_utility.png")
    for name in results.partition.unique():
        plot_convergence(history, name, fig_dir / f"dp_convergence_{name}.png")

    probe = model_fn()
    meta = {"disclaimer": DISCLAIMER, "config_file": config_path.as_posix(), "config": cfg,
            "privacy": pcfg, "privacy_unit": "one training example of one client (example-level DP, not client-level)",
            "data_file": dcfg["file"], "data_sha256": sha256(RAW_DIR / dcfg["file"]), "split_sizes": split.sizes(),
            "seeds": seeds, "model_parameters": count_parameters(probe), "model_bytes": state_nbytes(probe.state_dict()),
            "opacus_version": opacus.__version__, "torch": torch.__version__,
            "environment": {"python": sys.version.split()[0], "platform": platform.platform(), "cpu_count": os.cpu_count()},
            "runtime_seconds_total": time.perf_counter() - t_total, "finished_at": time.strftime("%Y-%m-%d %H:%M:%S %z")}
    (out_dir / "run_metadata.json").write_text(json.dumps(meta, indent=2, default=str), encoding="utf-8")
    write_report(meta, summary, accounting, out_dir / "report.md")
    cols = ["partition", "algorithm", "noise_multiplier", "epsilon_max", "roc_auc", "accuracy", "recall_class1", "f1_class1", "train_seconds"]
    with pd.option_context("display.width", 200):
        print("\n" + summary[cols].round(4).to_string(index=False))
    print(f"\nTotal runtime {meta['runtime_seconds_total']:.1f}s. Outputs in {out_dir}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", type=Path, default=ROOT / "configs" / "federated_dp.yaml")
    main(parser.parse_args().config)
