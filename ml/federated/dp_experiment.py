"""Optional privacy-utility experiment: FedAvg / FedProx with and without example-level DP-SGD.

Run from the repository root:
    python -m ml.federated.dp_experiment --config configs/federated_dp.yaml

The non-private runs are ordinary FedAvg/FedProx (data locality only, no formal privacy).
The private runs replace each client's local SGD by Opacus DP-SGD (per-example clipping,
Gaussian noise, RDP accountant). The privacy unit is one training example of one client;
epsilon is reported per client and summarized by its maximum. This is NOT client-level DP.
"""

