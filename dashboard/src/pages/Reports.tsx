import { useEffect, useState } from "react";
import {
  Check,
  Copy,
  Download,
  Eye,
  FileCode,
  FileSpreadsheet,
  FileText,
  RotateCcw,
} from "lucide-react";
import { api, type ReportItem } from "../api";
import { bytesHuman } from "../format";
import { Card, EmptyState, ErrorState, Loading, PageHeader } from "../components/ui";

export default function Reports() {
  const [reports, setReports] = useState<ReportItem[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [generating, setGenerating] = useState<string | null>(null);
  const [selectedReport, setSelectedReport] = useState<ReportItem | null>(null);
  const [copied, setCopied] = useState(false);

  const loadReports = async () => {
    setLoading(true);
    setError(null);
    try {
      const list = await api.reports.list();
      setReports(list);
      if (list.length > 0 && !selectedReport) {
        setSelectedReport(list[0]);
      }
    } catch (e: unknown) {
      setError(e instanceof Error ? e.message : String(e));
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadReports();
  }, []);

  const handleGenerate = async (kind: string) => {
    setGenerating(kind);
    try {
      const generated = await api.reports.generate(kind);
      setReports((prev) => [generated, ...prev]);
      setSelectedReport(generated);
    } catch (e: unknown) {
      alert(`Report generation failed: ${e instanceof Error ? e.message : String(e)}`);
    } finally {
      setGenerating(null);
    }
  };

  const handleDownload = (rep: ReportItem) => {
    const blob = new Blob([rep.preview_text || `# ${rep.title}\nGenerated by MediFederate AI.`], {
      type: rep.media_type,
    });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = rep.filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const handleCopy = () => {
    if (!selectedReport?.preview_text) return;
    navigator.clipboard.writeText(selectedReport.preview_text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const REPORT_TYPES = [
    {
      kind: "comparison_csv",
      title: "Experiment Comparison CSV",
      desc: "Tabular raw metrics for all models and federated seeds",
      icon: <FileSpreadsheet className="h-4 w-4 text-emerald-600" />,
    },
    {
      kind: "centralized_vs_federated",
      title: "Centralized vs Federated Report",
      desc: "Statistical parity and data preservation audit",
      icon: <FileText className="h-4 w-4 text-teal-600" />,
    },
    {
      kind: "fedavg_vs_fedprox",
      title: "FedAvg vs FedProx Analysis",
      desc: "Convergence stability with proximal regularization",
      icon: <FileCode className="h-4 w-4 text-sky-600" />,
    },
    {
      kind: "iid_vs_noniid",
      title: "IID vs Non-IID Analysis",
      desc: "Client Dirichlet skew and heterogeneity study",
      icon: <FileText className="h-4 w-4 text-indigo-600" />,
    },
    {
      kind: "full_research_pdf",
      title: "Full platform report (PDF)",
      desc: "Executive summary, methodology, and results",
      icon: <FileText className="h-4 w-4 text-rose-600" />,
    },
  ];

  return (
    <div className="space-y-6">
      {/* Header */}
      <PageHeader
        title="Reports"
        description="Export aggregated comparisons. Patient-level records are never included."
        actions={
          <button onClick={loadReports} className="btn-secondary" title="Refresh">
            <RotateCcw className="h-4 w-4 text-slate-500" />
            Refresh
          </button>
        }
      />

      <div>
        <h2 className="mb-3 text-sm font-semibold text-slate-800">Generate</h2>
        <div className="grid grid-cols-1 gap-3 sm:grid-cols-2 lg:grid-cols-5">
          {REPORT_TYPES.map((rt) => (
            <div
              key={rt.kind}
              className="card flex cursor-pointer flex-col justify-between transition-colors hover:border-teal-400/80"
              onClick={() => handleGenerate(rt.kind)}
            >
              <div>
                <div className="mb-3 flex h-9 w-9 items-center justify-center rounded-xl bg-slate-50">
                  {rt.icon}
                </div>
                <h3 className="text-sm font-semibold leading-snug text-slate-900">{rt.title}</h3>
                <p className="mt-1.5 text-sm leading-relaxed text-slate-500">{rt.desc}</p>
              </div>
              <button disabled={generating === rt.kind} className="btn-teal mt-4 w-full">
                {generating === rt.kind ? "Generating…" : "Generate"}
              </button>
            </div>
          ))}
        </div>
      </div>

      {/* Main Split: Reports List (5 cols) & Live Preview Area (7 cols) */}
      <div className="grid gap-6 lg:grid-cols-12">
        {/* Left List */}
        <div className="lg:col-span-5 space-y-4">
          <Card
            title={
              <div className="flex items-center justify-between w-full">
                <span className="text-[11px] font-semibold uppercase tracking-[0.12em] text-slate-500">
                  Generated ({reports.length})
                </span>
              </div>
            }
          >
            {loading ? (
              <Loading message="Loading reports…" />
            ) : error ? (
              <ErrorState message={error} />
            ) : reports.length === 0 ? (
              <EmptyState message="No reports have been generated yet." />
            ) : (
              <div className="divide-y divide-slate-100">
                {reports.map((rep) => {
                  const isSelected = selectedReport?.id === rep.id;
                  return (
                    <div
                      key={rep.id}
                      onClick={() => setSelectedReport(rep)}
                      className={`p-3 transition-colors cursor-pointer rounded ${
                        isSelected ? "bg-teal-50/70 border border-teal-200" : "hover:bg-slate-50"
                      }`}
                    >
                      <div className="flex items-start justify-between">
                        <div className="flex items-center gap-2">
                          <FileText className={`h-4 w-4 shrink-0 ${isSelected ? "text-teal-700" : "text-slate-400"}`} />
                          <h4 className="text-xs font-semibold text-slate-900 line-clamp-1">{rep.title}</h4>
                        </div>
                        <span className="badge-neutral text-[10px] uppercase font-mono">{rep.media_type.split("/")[1] || "txt"}</span>
                      </div>
                      <div className="mt-1.5 flex items-center justify-between text-[11px] text-slate-500">
                        <span>{new Date(rep.created_at).toLocaleDateString()}</span>
                        <span>{bytesHuman(rep.size_bytes)}</span>
                        <button
                          onClick={(e) => {
                            e.stopPropagation();
                            handleDownload(rep);
                          }}
                          className="text-teal-700 hover:text-teal-900 font-semibold inline-flex items-center gap-1"
                        >
                          <Download className="h-3 w-3" />
                          Download
                        </button>
                      </div>
                    </div>
                  );
                })}
              </div>
            )}
          </Card>
        </div>

        {/* Right Preview Area */}
        <div className="lg:col-span-7 space-y-4">
          {selectedReport ? (
            <Card
              title={
                <div className="flex items-center justify-between w-full">
                  <div className="flex items-center gap-2">
                    <Eye className="h-4 w-4 text-teal-600" />
                    <span className="text-xs font-bold text-slate-900">{selectedReport.title}</span>
                  </div>
                  <div className="flex items-center gap-2">
                    <button
                      onClick={handleCopy}
                      className="btn-secondary text-xs px-2 py-1"
                      title="Copy content"
                    >
                      {copied ? <Check className="h-3 w-3 text-emerald-600" /> : <Copy className="h-3 w-3" />}
                      {copied ? "Copied" : "Copy"}
                    </button>
                    <button
                      onClick={() => handleDownload(selectedReport)}
                      className="btn-teal text-xs px-2.5 py-1"
                      title="Download report"
                    >
                      <Download className="h-3 w-3" />
                      Download
                    </button>
                  </div>
                </div>
              }
              subtitle={
                <span className="text-[11px] text-slate-400 font-mono">
                  Filename: {selectedReport.filename} · Size: {bytesHuman(selectedReport.size_bytes)}
                </span>
              }
            >
              <div className="rounded border border-slate-200 bg-slate-900 p-4 font-mono text-xs text-slate-200 overflow-x-auto max-h-[500px] leading-relaxed whitespace-pre-wrap selection:bg-teal-700">
                {selectedReport.preview_text || `# ${selectedReport.title}\nNo preview available.`}
              </div>
            </Card>
          ) : (
            <EmptyState
              title="No report selected"
              message="Choose a document from the list to preview and download."
            />
          )}
        </div>
      </div>
    </div>
  );
}
